# ================================================================
# HELPER FUNCTIONS
# ================================================================

def sp(key: str) -> int:
    """دریافت مقدار spacing"""
    return SPACING.get(key, 0)


def pad(key: str):
    """دریافت padding"""
    return PADDING.get(key, (0, 0))


def h(key: str) -> int:
    """دریافت ارتفاع"""
    return HEIGHTS.get(key, 0)


def w(key: str) -> int:
    """دریافت عرض"""
    return WIDTHS.get(key, 0)


def radius(key: str) -> int:
    """دریافت شعاع"""
    return RADIUS.get(key, 0)


